// Gestió «proves» deployment (gestioproves.grupscoutparpallo.com). The only remote target this repository can
// publish; production Gestió stays blocked in deploy.js. Commands:
//   npm run proves:check   validate gestio/wrangler.proves.toml and the Cloudflare login
//   npm run proves:deploy  build the demo snapshot, apply remote migrations, deploy the Worker
//   npm run proves:reset   restore the remote D1 to the demo now (the Worker also does it every night)
import { spawnSync } from 'node:child_process';
import { mkdtempSync, readFileSync, realpathSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildProvesSnapshot, restoreSqlFile } from '../proves/snapshot.js';

const gestio = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const repo = resolve(gestio, '..');
const configPath = resolve(gestio, 'wrangler.proves.toml');
const generated = resolve(gestio, 'proves', 'snapshot.generated.js');
const wrangler = resolve(repo, 'node_modules', '.bin', 'wrangler');
const DATABASE = 'parpallo-gestio-proves';
const HOST = 'gestioproves.grupscoutparpallo.com';

const value = (config, key) => config.match(new RegExp(`^${key}\\s*=\\s*"([^"]*)"\\s*$`, 'm'))?.[1];

/** Refuses anything but the reviewed STAGING shape: Access configured, demo selector, one EU D1, no R2, no local provider. */
export function assertProvesConfig(config) {
  const errors = [];
  if (/REPLACE_/.test(config)) errors.push('Falten valors per omplir (REPLACE_…): Access i D1.');
  const expected = { name: 'parpallo-gestio-proves', main: 'proves/worker.js', APP_ENV: 'production', DEPLOYMENT_ENVIRONMENT: 'STAGING',
    STAGING_DEMO_LOGIN: 'enabled', database_name: DATABASE };
  for (const [key, wanted] of Object.entries(expected)) if (value(config, key) !== wanted) errors.push(`${key} ha de ser "${wanted}".`);
  if (!/^https:\/\/[a-z0-9-]+\.cloudflareaccess\.com$/.test(value(config, 'ACCESS_ISSUER') ?? '')) errors.push('ACCESS_ISSUER ha de ser https://<equip>.cloudflareaccess.com');
  if (!/^[a-f0-9]{64}$/.test(value(config, 'ACCESS_AUDIENCE') ?? '')) errors.push('ACCESS_AUDIENCE ha de ser l’AUD tag (64 hex).');
  if (!/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/.test(value(config, 'database_id') ?? '')) errors.push('database_id no és un UUID de D1.');
  if (/DEV_IDENTITY_PROVIDER|r2_buckets|kv_namespaces|durable_objects|\[\[services\]\]|\[env\./.test(config)) errors.push('Sense proveïdor local, R2, KV, DO, serveis ni entorns addicionals.');
  if (!/^workers_dev\s*=\s*false\s*$/m.test(config) || !/^preview_urls\s*=\s*false\s*$/m.test(config)) errors.push('workers_dev i preview_urls han de ser false.');
  const routes = config.match(/^routes\s*=\s*(.+)$/m)?.[1] ?? '';
  if (routes !== `[{ pattern = "${HOST}", custom_domain = true }]`) errors.push(`L’única ruta ha de ser el domini propi ${HOST}.`);
  if (errors.length) throw new Error(`Configuració de proves no vàlida:\n- ${errors.join('\n- ')}`);
}

function run(args, { capture = false } = {}) {
  const result = spawnSync(wrangler, args, { cwd: gestio, encoding: 'utf8', env: { ...process.env, WRANGLER_SEND_METRICS: 'false' },
    stdio: capture ? ['ignore', 'pipe', 'pipe'] : 'inherit', maxBuffer: 16 * 1024 * 1024 });
  if (result.error || result.status !== 0) throw new Error(`wrangler ${args[0]} ha fallat${capture ? `: ${result.stderr || result.stdout}` : ''}`);
  return result.stdout;
}
const remote = args => [...args, '--remote', '--config', configPath];

function assertCommitted() {
  const status = spawnSync('git', ['status', '--porcelain', '--', 'gestio'], { cwd: repo, encoding: 'utf8' });
  if (status.status !== 0) throw new Error('No s’ha pogut comprovar git status.');
  if (status.stdout.trim()) throw new Error(`Només es publica codi commitejat. Canvis pendents a gestio/:\n${status.stdout}`);
}

function check() {
  assertProvesConfig(readFileSync(configPath, 'utf8'));
  const who = run(['whoami'], { capture: true });
  if (/not authenticated/i.test(who)) throw new Error('Inicia sessió a Cloudflare: npx wrangler login');
}

function writeSnapshot() {
  const snapshot = buildProvesSnapshot();
  writeFileSync(generated, `// Generated by gestio/scripts/proves.js — do not edit or commit.\nexport default ${JSON.stringify(snapshot)};\n`);
  return snapshot;
}

function remoteLatestMigration() {
  const raw = run(remote(['d1', 'execute', DATABASE, '--command', 'SELECT name FROM d1_migrations ORDER BY id DESC LIMIT 1', '--json']), { capture: true });
  return JSON.parse(raw.slice(raw.indexOf('[')))[0]?.results?.[0]?.name ?? null;
}

function reset(snapshot = buildProvesSnapshot()) {
  const latest = remoteLatestMigration();
  if (latest !== snapshot.latestMigration) throw new Error(`L’esquema remot (${latest}) no coincideix amb la demo (${snapshot.latestMigration}). Executa proves:deploy.`);
  const temporary = mkdtempSync(resolve(tmpdir(), 'gestio-proves-'));
  try {
    const file = resolve(temporary, 'restore.sql');
    // The nightly state restarts too: the next night compares against this fresh demo.
    writeFileSync(file, restoreSqlFile(snapshot) + 'DROP TABLE IF EXISTS proves_reset_state;\n');
    run(remote(['d1', 'execute', DATABASE, '--file', file, '--yes']));
  } finally { rmSync(temporary, { recursive: true, force: true }); }
  console.log(`Demo restaurada a ${DATABASE}: ${snapshot.rows} files.`);
}

export function main(args = process.argv.slice(2)) {
  const [command, ...flags] = args;
  if (!['check', 'deploy', 'reset'].includes(command) || flags.some(flag => flag !== '--reset') || (flags.length && command !== 'deploy'))
    throw new Error('Ús: proves.js check | deploy [--reset] | reset');
  check();
  if (command === 'check') { console.log('Configuració de proves correcta i sessió de Cloudflare activa.'); return; }
  if (command === 'reset') { reset(); return; }
  assertCommitted();
  const snapshot = writeSnapshot();
  run(remote(['d1', 'migrations', 'apply', DATABASE]));
  run(['deploy', '--config', configPath]);
  if (flags.includes('--reset')) reset(snapshot);
  console.log(`Publicat a https://${HOST}`);
}

if (process.argv[1] && realpathSync(resolve(process.argv[1])) === realpathSync(fileURLToPath(import.meta.url))) {
  try { main(); } catch (error) { console.error(error.message); process.exitCode = 1; }
}
